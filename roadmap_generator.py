# ── Generator ──────────────────────────────────────────────────────────────

def generate_roadmap(user_goal):
    """Generate RoadmapStage records for a given UserGoal.

    Uses template data keyed by (skill_name, level, target_months).
    Falls back gracefully if the exact combination is missing.
    """
    skill_name = user_goal.skill.name
    level = user_goal.level
    months = user_goal.target_months

    # Get template for this skill
    skill_templates = STAGE_TEMPLATES.get(skill_name)
    if not skill_templates:
        return _fallback_generate(user_goal)

    # Get level template
    level_templates = skill_templates.get(level)
    if not level_templates:
        # Try the closest level
        level_templates = _closest_level(skill_templates, level)

    # Get duration template
    duration = _closest_duration(level_templates, months)
    stage_data = level_templates.get(duration, list(level_templates.values())[0])

    # Create RoadmapStage records
    stages = []
    for i, (name, desc, points) in enumerate(stage_data):
        stage = RoadmapStage(
            user_goal_id=user_goal.id,
            skill_id=user_goal.skill_id,
            stage_order=i + 1,
            name=name,
            description=desc,
            knowledge_points=json.dumps(points, ensure_ascii=False),
            status='current' if i == 0 else 'pending',
        )
        db.session.add(stage)
        stages.append(stage)

    db.session.commit()
    return stages


def _closest_level(level_templates, level):
    """Find the closest available level template."""
    level_order = ['零基础', '初级', '中级', '高级']
    if level in level_templates:
        return level_templates[level]

    idx = level_order.index(level) if level in level_order else 0
    # Search outward from the requested level
    for offset in range(1, 4):
        if idx - offset >= 0 and level_order[idx - offset] in level_templates:
            return level_templates[level_order[idx - offset]]
        if idx + offset < 4 and level_order[idx + offset] in level_templates:
            return level_templates[level_order[idx + offset]]
    return list(level_templates.values())[0]


def _closest_duration(templates, months):
    """Find the closest available duration."""
    avail = sorted(templates.keys())
    if months in avail:
        return months
    if not avail:
        return 3
    # Find nearest
    return min(avail, key=lambda d: abs(d - months))


def _fallback_generate(user_goal):
    """Generic fallback when no template exists."""
    stages_data = [
        ('第一阶段', '入门基础', ['了解基本概念', '掌握核心知识', '完成基础练习']),
        ('第二阶段', '进阶学习', ['深入学习', '实践练习', '项目应用']),
        ('第三阶段', '高阶提升', ['高级主题', '综合运用', '独立项目']),
    ]
    stages = []
    for i, (name, desc, points) in enumerate(stages_data):
        stage = RoadmapStage(
            user_goal_id=user_goal.id,
            skill_id=user_goal.skill_id,
            stage_order=i + 1,
            name=name,
            description=desc,
            knowledge_points=json.dumps(points, ensure_ascii=False),
            status='current' if i == 0 else 'pending',
        )
        db.session.add(stage)
        stages.append(stage)
    db.session.commit()
    return stages
